/** Small pixel-style icons drawn as SVG rectangles (16x16 grid), coloured with currentColor. */
type Props = { size?: number; className?: string };

function Pixels({ rows, size = 24, className }: Props & { rows: string[] }) {
  const rects: JSX.Element[] = [];
  rows.forEach((row, y) => [...row].forEach((c, x) => {
    if (c === '#') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" />);
    else if (c === '+') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" opacity=".45" />);
  }));
  return <svg className={className} width={size} height={size} viewBox="0 0 16 16" fill="currentColor" shapeRendering="crispEdges" aria-hidden="true">{rects}</svg>;
}

